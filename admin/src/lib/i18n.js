export function createT(lang) {
  const pack = strings[lang] || strings.uz;
  return (key, ...args) => {
    // Tanlangan tilda topilmasa o'zbekchasiga, u ham bo'lmasa kalitning
    // o'ziga tushamiz — panel hech qachon bo'sh joy ko'rsatmaydi.
    const value = pack[key] ?? strings.uz[key] ?? key;
    return typeof value === 'function' ? value(...args) : value;
  };
}

/**
 * Do'konning o'z ma'lumotini (mahsulot nomi, kategoriya...) tanlangan tilda
 * oladi. Ruscha to'ldirilmagan bo'lsa o'zbekchasi ko'rsatiladi — bo'sh katak
 * chiqmaydi.
 */
export function pick(obj, field, lang) {
  const suffix = lang === 'ru' ? 'Ru' : 'Uz';
  return obj?.[`${field}${suffix}`] || obj?.[`${field}Uz`] || '';
}

